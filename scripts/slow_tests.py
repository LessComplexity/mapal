#!/usr/bin/env python3
"""The slow tests, and the nextest config built from them.

`.config/slow-tests.txt` lists the tests that take more than a few seconds (one `binary<TAB>test` per line):
nearly all generated-program tests that run many programs through the GPU emulator. 129 of 1,860 tests take
~98% of the suite's time. From that one list this script writes `.config/nextest.toml`:

  - locally (`cargo nextest run --workspace --release`): the slow tests run at most two at a time (each
    emulated program already spreads over every core), everything else in parallel;
  - profile `quick` (CI, every push): the suite without the slow tests;
  - profile `full` (CI, nightly, sharded): everything.

Usage:
  scripts/slow_tests.py                         rewrite .config/nextest.toml from the list
  scripts/slow_tests.py --from-log LOG [--over SECONDS]
                                                re-measure: take every test slower than SECONDS (default 10)
                                                from a `cargo nextest run` output, rewrite the list and the config
  scripts/slow_tests.py --check                 exit 1 if .config/nextest.toml is not what the list gives
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = ROOT / ".config" / "slow-tests.txt"
CONFIG = ROOT / ".config" / "nextest.toml"
LINE = re.compile(r"^\s+(PASS|FAIL|SIGTERM|SIGKILL|TIMEOUT)\s+\[\s*([0-9.]+)s\]\s+\(\s*\d+/\d+\)\s+(\S+)\s+(\S+)")

TEMPLATE = """\
# GENERATED by scripts/slow_tests.py from .config/slow-tests.txt: edit the list (or re-measure), not this file.

[test-groups]
# Real-GPU tests (they skip themselves without nvcc): each fans out over the GPU's free memory on its own.
gpu = {{ max-threads = 1 }}
# The slow tests: each runs many programs through the CPU emulator, which uses every core by itself.
heavy = {{ max-threads = 2 }}

[profile.default]
test-threads = 16
slow-timeout = {{ period = "120s" }}
fail-fast = false

[[profile.default.overrides]]
filter = 'package(mapal-backend-cuda) and kind(test)'
test-group = 'gpu'

[[profile.default.overrides]]
filter = '''
{slow}
'''
test-group = 'heavy'

[profile.default.junit]
path = "junit.xml"

# CI on every push: everything but the slow tests (they run in the nightly `full` run).
[profile.quick]
test-threads = "num-cpus"
default-filter = '''
not (
{slow}
)
'''

# CI nightly: everything, sharded with --partition.
[profile.full]
test-threads = "num-cpus"
"""


def read_list() -> list[tuple[str, str]]:
    rows = []
    for line in LIST.read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            binary, test = line.split("\t")
            rows.append((binary, test))
    return rows


def render(rows: list[tuple[str, str]]) -> str:
    terms = " |\n".join(f"(binary_id(={b}) & test(={t}))" for b, t in rows)
    return TEMPLATE.format(slow=terms)


def from_log(path: str, over: float) -> list[tuple[str, str]]:
    slow = set()
    for line in pathlib.Path(path).read_text(errors="replace").splitlines():
        m = LINE.match(line)
        if m and float(m.group(2)) > over:
            slow.add((m.group(3), m.group(4)))
    return sorted(slow)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from-log")
    ap.add_argument("--over", type=float, default=10.0)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.from_log:
        rows = from_log(a.from_log, a.over)
        head = f"# Tests slower than {a.over:g} s (binary<TAB>test), measured by scripts/slow_tests.py --from-log.\n"
        LIST.write_text(head + "".join(f"{b}\t{t}\n" for b, t in rows))
    want = render(read_list())
    if a.check:
        if not CONFIG.exists() or CONFIG.read_text() != want:
            print("slow_tests: .config/nextest.toml is stale; run scripts/slow_tests.py", file=sys.stderr)
            return 1
        print(f"slow_tests: ok ({len(read_list())} slow tests)")
        return 0
    CONFIG.write_text(want)
    print(f"slow_tests: wrote .config/nextest.toml ({len(read_list())} slow tests)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
