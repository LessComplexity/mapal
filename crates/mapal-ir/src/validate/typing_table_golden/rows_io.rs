//! The typing-table golden rows for `Index`, `Zip`, `Enumerate`, `Update`,
//! I/O (`Print`, `Read`, `TimeMs`), the loop edges and `Output` (DESIGN §5.1,
//! the second part in the table's order).

use super::*;

/// The rows from `Index` through `Output`.
pub(super) fn io_rows(fx: &Fx) -> Vec<Case> {
    use Operation::*;
    let (i32t, i64t) = (int(32), int(64));
    let p = fx.plain; // target-agnostic ops route here (target unread by them)
    let m = fx.merge; // loop ops need a LoopMerge target

    vec![
        // Index: (Array{T,n}, I) -> T.
        (
            "Index ok",
            Index,
            tup(&[arr(i32t.clone(), 3), i32t.clone()]),
            i32t.clone(),
            p,
            true,
        ),
        // I = any Core integer scalar, unsigned included.
        (
            "Index u8 idx ok",
            Index,
            tup(&[arr(i32t.clone(), 3), Ty::u8()]),
            i32t.clone(),
            p,
            true,
        ),
        (
            "Index idx not int",
            Index,
            tup(&[arr(i32t.clone(), 3), f32t()]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Index tty not elem",
            Index,
            tup(&[arr(i32t.clone(), 3), i32t.clone()]),
            f32t(),
            p,
            false,
        ),
        (
            "Index src not array",
            Index,
            tup(&[i32t.clone(), i32t.clone()]),
            i32t.clone(),
            p,
            false,
        ),
        // Zip (ADR-0018): ([A;n], [B;n]) -> [(A,B);n]. Pure typing; the
        // n<=i32::MAX bound is NOT an Enumerate concern and is not tested here.
        (
            "Zip ok i32/f32",
            Zip,
            tup(&[arr(i32t.clone(), 4), arr(f32t(), 4)]),
            arr(tup(&[i32t.clone(), f32t()]), 4),
            p,
            true,
        ),
        (
            "Zip size mismatch",
            Zip,
            tup(&[arr(i32t.clone(), 4), arr(f32t(), 3)]),
            arr(tup(&[i32t.clone(), f32t()]), 4),
            p,
            false,
        ),
        (
            "Zip result size mismatch",
            Zip,
            tup(&[arr(i32t.clone(), 4), arr(f32t(), 4)]),
            arr(tup(&[i32t.clone(), f32t()]), 3),
            p,
            false,
        ),
        (
            "Zip wrong elem order",
            Zip,
            tup(&[arr(i32t.clone(), 4), arr(f32t(), 4)]),
            arr(tup(&[f32t(), i32t.clone()]), 4),
            p,
            false,
        ),
        (
            "Zip source not tuple",
            Zip,
            arr(i32t.clone(), 4),
            arr(tup(&[i32t.clone(), f32t()]), 4),
            p,
            false,
        ),
        (
            "Zip source not arrays",
            Zip,
            tup(&[i32t.clone(), f32t()]),
            arr(tup(&[i32t.clone(), f32t()]), 4),
            p,
            false,
        ),
        (
            "Zip target not array of pair",
            Zip,
            tup(&[arr(i32t.clone(), 4), arr(f32t(), 4)]),
            arr(i32t.clone(), 4),
            p,
            false,
        ),
        // Enumerate (ADR-0018): [A;n] -> [(i32, A);n].
        (
            "Enumerate ok",
            Enumerate,
            arr(f32t(), 4),
            arr(tup(&[i32t.clone(), f32t()]), 4),
            p,
            true,
        ),
        (
            "Enumerate size mismatch",
            Enumerate,
            arr(f32t(), 4),
            arr(tup(&[i32t.clone(), f32t()]), 3),
            p,
            false,
        ),
        (
            "Enumerate wrong index component",
            Enumerate,
            arr(f32t(), 4),
            arr(tup(&[i64t.clone(), f32t()]), 4),
            p,
            false,
        ),
        (
            "Enumerate wrong elem",
            Enumerate,
            arr(f32t(), 4),
            arr(tup(&[i32t.clone(), i32t.clone()]), 4),
            p,
            false,
        ),
        (
            "Enumerate source not array",
            Enumerate,
            i32t.clone(),
            arr(tup(&[i32t.clone(), f32t()]), 4),
            p,
            false,
        ),
        (
            "Enumerate target not array of pair",
            Enumerate,
            arr(f32t(), 4),
            arr(f32t(), 4),
            p,
            false,
        ),
        // Update (ADR-0021): (Array{T,n}, I, T) -> Array{T,n}.
        (
            "Update ok",
            Update,
            tup(&[arr(i32t.clone(), 3), i32t.clone(), i32t.clone()]),
            arr(i32t.clone(), 3),
            p,
            true,
        ),
        // I = any Core integer scalar, unsigned included (mirrors Index).
        (
            "Update u8 idx ok",
            Update,
            tup(&[arr(i32t.clone(), 3), Ty::u8(), i32t.clone()]),
            arr(i32t.clone(), 3),
            p,
            true,
        ),
        (
            "Update idx not int",
            Update,
            tup(&[arr(i32t.clone(), 3), f32t(), i32t.clone()]),
            arr(i32t.clone(), 3),
            p,
            false,
        ),
        (
            "Update val not elem",
            Update,
            tup(&[arr(i32t.clone(), 3), i32t.clone(), f32t()]),
            arr(i32t.clone(), 3),
            p,
            false,
        ),
        (
            "Update src not array",
            Update,
            tup(&[i32t.clone(), i32t.clone(), i32t.clone()]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Update wrong arity",
            Update,
            tup(&[arr(i32t.clone(), 3), i32t.clone()]),
            arr(i32t.clone(), 3),
            p,
            false,
        ),
        (
            "Update target size mismatch",
            Update,
            tup(&[arr(i32t.clone(), 3), i32t.clone(), i32t.clone()]),
            arr(i32t.clone(), 4),
            p,
            false,
        ),
        (
            "Update target not source array",
            Update,
            tup(&[arr(i32t.clone(), 3), i32t.clone(), i32t.clone()]),
            arr(f32t(), 3),
            p,
            false,
        ),
        // Print{newline}: (IoToken, P) -> IoToken, P printable (N, Bool, Str).
        (
            "Print int",
            Print { newline: false },
            tup(&[Ty::IoToken, i32t.clone()]),
            Ty::IoToken,
            p,
            true,
        ),
        (
            "Println str",
            Print { newline: true },
            tup(&[Ty::IoToken, Ty::Str]),
            Ty::IoToken,
            p,
            true,
        ),
        (
            "Print bool",
            Print { newline: false },
            tup(&[Ty::IoToken, Ty::Bool]),
            Ty::IoToken,
            p,
            true,
        ),
        (
            "Print first not token",
            Print { newline: false },
            tup(&[i32t.clone(), i32t.clone()]),
            Ty::IoToken,
            p,
            false,
        ),
        (
            "Print tty not token",
            Print { newline: false },
            tup(&[Ty::IoToken, i32t.clone()]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Print P not printable",
            Print { newline: false },
            tup(&[Ty::IoToken, tup(&[i32t.clone(), i32t.clone()])]),
            Ty::IoToken,
            p,
            false,
        ),
        // Read (ADR-0045): (IoToken, Str) -> (IoToken, [T; n]).
        (
            "Read f32 ok",
            Read,
            tup(&[Ty::IoToken, Ty::Str]),
            tup(&[Ty::IoToken, arr(f32t(), 4)]),
            p,
            true,
        ),
        (
            "Read bf16 ok",
            Read,
            tup(&[Ty::IoToken, Ty::Str]),
            tup(&[Ty::IoToken, arr(Ty::Narrow(crate::NarrowFloat::Bf16), 4)]),
            p,
            true,
        ),
        (
            "Read path not str",
            Read,
            tup(&[Ty::IoToken, i32t.clone()]),
            tup(&[Ty::IoToken, arr(f32t(), 4)]),
            p,
            false,
        ),
        (
            "Read target not array",
            Read,
            tup(&[Ty::IoToken, Ty::Str]),
            tup(&[Ty::IoToken, f32t()]),
            p,
            false,
        ),
        (
            // full-model: a nested array is a readable value (its leaves
            // in order, no padding).
            "Read nested array",
            Read,
            tup(&[Ty::IoToken, Ty::Str]),
            tup(&[Ty::IoToken, arr(arr(f32t(), 2), 4)]),
            p,
            true,
        ),
        (
            "Read padded record",
            Read,
            tup(&[Ty::IoToken, Ty::Str]),
            tup(&[Ty::IoToken, arr(tup(&[f32t(), Ty::u8()]), 4)]),
            p,
            false,
        ),
        (
            "Read bool elements",
            Read,
            tup(&[Ty::IoToken, Ty::Str]),
            tup(&[Ty::IoToken, arr(Ty::Bool, 4)]),
            p,
            false,
        ),
        // TimeMs (plan-time-builtin): IoToken -> (IoToken, f64).
        (
            "TimeMs ok",
            TimeMs,
            Ty::IoToken,
            tup(&[Ty::IoToken, Ty::f64()]),
            p,
            true,
        ),
        (
            "TimeMs source not token",
            TimeMs,
            i32t.clone(),
            tup(&[Ty::IoToken, Ty::f64()]),
            p,
            false,
        ),
        (
            "TimeMs target not pair",
            TimeMs,
            Ty::IoToken,
            Ty::IoToken,
            p,
            false,
        ),
        (
            "TimeMs target first not token",
            TimeMs,
            Ty::IoToken,
            tup(&[i32t.clone(), Ty::f64()]),
            p,
            false,
        ),
        (
            "TimeMs target second not f64",
            TimeMs,
            Ty::IoToken,
            tup(&[Ty::IoToken, f32t()]),
            p,
            false,
        ),
        // LoopEnter: U -> U, target kind LoopMerge.
        (
            "LoopEnter ok",
            LoopEnter,
            i32t.clone(),
            i32t.clone(),
            m,
            true,
        ),
        (
            "LoopEnter tgt not merge",
            LoopEnter,
            i32t.clone(),
            i32t.clone(),
            p,
            false,
        ),
        (
            "LoopEnter sty!=tty",
            LoopEnter,
            i32t.clone(),
            f32t(),
            m,
            false,
        ),
        // LoopBack: (U, Bool) -> U, target kind LoopMerge.
        (
            "LoopBack ok",
            LoopBack,
            tup(&[i32t.clone(), Ty::Bool]),
            i32t.clone(),
            m,
            true,
        ),
        (
            "LoopBack tgt not merge",
            LoopBack,
            tup(&[i32t.clone(), Ty::Bool]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "LoopBack 2nd not bool",
            LoopBack,
            tup(&[i32t.clone(), i32t.clone()]),
            i32t.clone(),
            m,
            false,
        ),
        (
            "LoopBack tty mismatch",
            LoopBack,
            tup(&[i32t.clone(), Ty::Bool]),
            f32t(),
            m,
            false,
        ),
        // LoopExit: (B, Bool) -> B.
        (
            "LoopExit ok",
            LoopExit,
            tup(&[i32t.clone(), Ty::Bool]),
            i32t.clone(),
            p,
            true,
        ),
        (
            "LoopExit 2nd not bool",
            LoopExit,
            tup(&[i32t.clone(), i32t.clone()]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "LoopExit tty mismatch",
            LoopExit,
            tup(&[i32t.clone(), Ty::Bool]),
            f32t(),
            p,
            false,
        ),
        // Output: T -> T (target-is-Return is the I8 clause in check_edges, not here).
        ("Output ok", Output, i32t.clone(), i32t.clone(), p, true),
        ("Output sty!=tty", Output, i32t.clone(), f32t(), p, false),
    ]
}
