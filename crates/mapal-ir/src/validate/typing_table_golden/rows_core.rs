//! The typing-table golden rows for products, scalar arithmetic and
//! comparisons, widening, `Phi`, calls, maps, folds and captured shapes
//! (DESIGN §5.1, the first part in the table's order).

use super::*;

/// One row: (label, op, source ty, target ty, target obj, expected §5.1 judgment).
pub(super) type Case = (&'static str, Operation, Ty, Ty, ObjectId, bool);

/// The rows from `Pair` through the ADR-0027 captured shapes.
pub(super) fn core_rows(fx: &Fx) -> Vec<Case> {
    use Operation::*;
    let (i32t, i64t) = (int(32), int(64));
    let p = fx.plain; // target-agnostic ops route here (target unread by them)

    vec![
        // Pair{slot,arity}: source = component ty at slot of the arity-N product target.
        (
            "Pair tuple slot0",
            Pair { slot: 0, arity: 2 },
            i32t.clone(),
            tup(&[i32t.clone(), f32t()]),
            p,
            true,
        ),
        (
            "Pair tuple slot1",
            Pair { slot: 1, arity: 2 },
            f32t(),
            tup(&[i32t.clone(), f32t()]),
            p,
            true,
        ),
        (
            "Pair struct slot0",
            Pair { slot: 0, arity: 2 },
            i32t.clone(),
            strct(&[("a", i32t.clone()), ("b", f32t())]),
            p,
            true,
        ),
        (
            "Pair array slot0",
            Pair { slot: 0, arity: 3 },
            i32t.clone(),
            arr(i32t.clone(), 3),
            p,
            true,
        ),
        (
            "Pair slot>=arity",
            Pair { slot: 2, arity: 2 },
            i32t.clone(),
            tup(&[i32t.clone(), f32t()]),
            p,
            false,
        ),
        (
            "Pair wrong comp ty",
            Pair { slot: 0, arity: 2 },
            f32t(),
            tup(&[i32t.clone(), f32t()]),
            p,
            false,
        ),
        (
            "Pair arity mismatch",
            Pair { slot: 0, arity: 3 },
            i32t.clone(),
            tup(&[i32t.clone(), f32t()]),
            p,
            false,
        ),
        (
            "Pair non-product tgt",
            Pair { slot: 0, arity: 2 },
            i32t.clone(),
            i32t.clone(),
            p,
            false,
        ),
        // Proj{index}: source Tuple/Struct; target = component ty at index. Arrays use Index.
        (
            "Proj tuple",
            Proj { index: 1 },
            tup(&[i32t.clone(), f32t()]),
            f32t(),
            p,
            true,
        ),
        (
            "Proj struct",
            Proj { index: 0 },
            strct(&[("a", i32t.clone()), ("b", f32t())]),
            i32t.clone(),
            p,
            true,
        ),
        (
            "Proj array rejected",
            Proj { index: 0 },
            arr(i32t.clone(), 2),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Proj wrong tty",
            Proj { index: 0 },
            tup(&[i32t.clone(), f32t()]),
            f32t(),
            p,
            false,
        ),
        (
            "Proj index oob",
            Proj { index: 5 },
            tup(&[i32t.clone(), f32t()]),
            i32t.clone(),
            p,
            false,
        ),
        // Add..Mod: (N,N) same N -> N.
        (
            "Add ok",
            Add,
            tup(&[i32t.clone(), i32t.clone()]),
            i32t.clone(),
            p,
            true,
        ),
        ("Sub ok", Sub, tup(&[f32t(), f32t()]), f32t(), p, true),
        (
            "Mul ok",
            Mul,
            tup(&[i32t.clone(), i32t.clone()]),
            i32t.clone(),
            p,
            true,
        ),
        ("Div ok", Div, tup(&[f32t(), f32t()]), f32t(), p, true),
        (
            "Mod ok",
            Mod,
            tup(&[i32t.clone(), i32t.clone()]),
            i32t.clone(),
            p,
            true,
        ),
        (
            "Add bool rejected",
            Add,
            tup(&[Ty::Bool, Ty::Bool]),
            Ty::Bool,
            p,
            false,
        ),
        (
            "Add mixed numeric",
            Add,
            tup(&[i32t.clone(), f32t()]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Add tty mismatch",
            Add,
            tup(&[i32t.clone(), i32t.clone()]),
            f32t(),
            p,
            false,
        ),
        ("Add not tuple", Add, i32t.clone(), i32t.clone(), p, false),
        // Neg: N -> same N (unary, direct edge).
        ("Neg i32", Neg, i32t.clone(), i32t.clone(), p, true),
        ("Neg f32", Neg, f32t(), f32t(), p, true),
        ("Neg bool rejected", Neg, Ty::Bool, Ty::Bool, p, false),
        (
            "Neg tty mismatch",
            Neg,
            i32t.clone(),
            i64t.clone(),
            p,
            false,
        ),
        // Eq/Neq: (A,A), A in N u {Bool} -> Bool.
        (
            "Eq numeric",
            Eq,
            tup(&[i32t.clone(), i32t.clone()]),
            Ty::Bool,
            p,
            true,
        ),
        ("Eq bool", Eq, tup(&[Ty::Bool, Ty::Bool]), Ty::Bool, p, true),
        (
            "Neq numeric",
            Neq,
            tup(&[f32t(), f32t()]),
            Ty::Bool,
            p,
            true,
        ),
        (
            "Eq mixed rejected",
            Eq,
            tup(&[i32t.clone(), f32t()]),
            Ty::Bool,
            p,
            false,
        ),
        (
            "Eq tty mismatch",
            Eq,
            tup(&[i32t.clone(), i32t.clone()]),
            i32t.clone(),
            p,
            false,
        ),
        // Str is printable (P) but NOT comparable — A ∈ N ∪ {Bool} only.
        (
            "Eq str rejected",
            Eq,
            tup(&[Ty::Str, Ty::Str]),
            Ty::Bool,
            p,
            false,
        ),
        // Lt/Gt/Le/Ge: (N,N) same N -> Bool (Bool is NOT ordered — the Eq-vs-Lt pin).
        (
            "Lt ok",
            Lt,
            tup(&[i32t.clone(), i32t.clone()]),
            Ty::Bool,
            p,
            true,
        ),
        ("Gt ok", Gt, tup(&[f32t(), f32t()]), Ty::Bool, p, true),
        (
            "Le ok",
            Le,
            tup(&[i32t.clone(), i32t.clone()]),
            Ty::Bool,
            p,
            true,
        ),
        (
            "Ge ok",
            Ge,
            tup(&[i32t.clone(), i32t.clone()]),
            Ty::Bool,
            p,
            true,
        ),
        (
            "Lt bool rejected",
            Lt,
            tup(&[Ty::Bool, Ty::Bool]),
            Ty::Bool,
            p,
            false,
        ),
        (
            "Lt mixed rejected",
            Lt,
            tup(&[i32t.clone(), f32t()]),
            Ty::Bool,
            p,
            false,
        ),
        // And/Or: (Bool,Bool) -> Bool.
        ("And ok", And, tup(&[Ty::Bool, Ty::Bool]), Ty::Bool, p, true),
        ("Or ok", Or, tup(&[Ty::Bool, Ty::Bool]), Ty::Bool, p, true),
        (
            "And numeric rejected",
            And,
            tup(&[i32t.clone(), i32t.clone()]),
            Ty::Bool,
            p,
            false,
        ),
        (
            "And tty mismatch",
            And,
            tup(&[Ty::Bool, Ty::Bool]),
            i32t.clone(),
            p,
            false,
        ),
        // Not: Bool -> Bool.
        ("Not ok", Not, Ty::Bool, Ty::Bool, p, true),
        ("Not sty mismatch", Not, i32t.clone(), Ty::Bool, p, false),
        ("Not tty mismatch", Not, Ty::Bool, i32t.clone(), p, false),
        // Widen (ADR-0029): the four explicit numeric lattice edges only.
        (
            "Widen i32 to i64",
            Widen,
            i32t.clone(),
            i64t.clone(),
            p,
            true,
        ),
        ("Widen i32 to f32", Widen, i32t.clone(), f32t(), p, true),
        ("Widen i32 to f64", Widen, i32t.clone(), Ty::f64(), p, true),
        ("Widen f32 to f64", Widen, f32t(), Ty::f64(), p, true),
        (
            "Widen i64 to f64 rejected",
            Widen,
            i64t.clone(),
            Ty::f64(),
            p,
            false,
        ),
        (
            "Widen identity rejected",
            Widen,
            i32t.clone(),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Widen array rejected",
            Widen,
            arr(i32t.clone(), 2),
            arr(i64t.clone(), 2),
            p,
            false,
        ),
        // Phi: (T,T,Bool) -> T, T token-free.
        (
            "Phi ok",
            Phi,
            tup(&[i32t.clone(), i32t.clone(), Ty::Bool]),
            i32t.clone(),
            p,
            true,
        ),
        (
            "Phi 2-tuple rejected",
            Phi,
            tup(&[i32t.clone(), Ty::Bool]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Phi cond not bool",
            Phi,
            tup(&[i32t.clone(), i32t.clone(), i32t.clone()]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Phi branches differ",
            Phi,
            tup(&[i32t.clone(), f32t(), Ty::Bool]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Phi tty mismatch",
            Phi,
            tup(&[i32t.clone(), i32t.clone(), Ty::Bool]),
            f32t(),
            p,
            false,
        ),
        (
            "Phi token rejected",
            Phi,
            tup(&[Ty::IoToken, Ty::IoToken, Ty::Bool]),
            Ty::IoToken,
            p,
            false,
        ),
        // Call(f): source = f.input ty, target = f.output ty (call_f: i32 -> f32).
        ("Call ok", Call(fx.call_f), i32t.clone(), f32t(), p, true),
        (
            "Call sty mismatch",
            Call(fx.call_f),
            f32t(),
            f32t(),
            p,
            false,
        ),
        (
            "Call tty mismatch",
            Call(fx.call_f),
            i32t.clone(),
            i32t.clone(),
            p,
            false,
        ),
        // Map{body}: Array{T,n} -> Array{U,n}, body: T -> U (map_f: i32 -> f32).
        (
            "Map ok",
            Map {
                body: fx.map_f,
                captures: 0,
            },
            arr(i32t.clone(), 3),
            arr(f32t(), 3),
            p,
            true,
        ),
        (
            "Map size mismatch",
            Map {
                body: fx.map_f,
                captures: 0,
            },
            arr(i32t.clone(), 3),
            arr(f32t(), 4),
            p,
            false,
        ),
        (
            "Map elem vs body in",
            Map {
                body: fx.map_f,
                captures: 0,
            },
            arr(f32t(), 3),
            arr(f32t(), 3),
            p,
            false,
        ),
        (
            "Map out vs body out",
            Map {
                body: fx.map_f,
                captures: 0,
            },
            arr(i32t.clone(), 3),
            arr(i32t.clone(), 3),
            p,
            false,
        ),
        (
            "Map not array",
            Map {
                body: fx.map_f,
                captures: 0,
            },
            i32t.clone(),
            f32t(),
            p,
            false,
        ),
        // Fold{body}: (Acc, Array{T,n}) -> Acc, body: (Acc,T) -> Acc (fold_f: (f32,i32) -> f32).
        (
            "Fold ok",
            Fold {
                body: fx.fold_f,
                captures: 0,
            },
            tup(&[f32t(), arr(i32t.clone(), 3)]),
            f32t(),
            p,
            true,
        ),
        // ADR-0027 captured shapes.
        (
            "Map+caps ok",
            Map {
                body: fx.map_caps_f,
                captures: 1,
            },
            tup(&[i32t.clone(), arr(i32t.clone(), 3)]),
            arr(f32t(), 3),
            p,
            true,
        ),
        (
            "Map+caps arity mismatch",
            Map {
                body: fx.map_caps_f,
                captures: 1,
            },
            tup(&[i32t.clone(), i32t.clone(), arr(i32t.clone(), 3)]),
            arr(f32t(), 3),
            p,
            false,
        ),
        (
            "Map+caps cap type mismatch",
            Map {
                body: fx.map_caps_f,
                captures: 1,
            },
            tup(&[f32t(), arr(i32t.clone(), 3)]),
            arr(f32t(), 3),
            p,
            false,
        ),
        (
            "Map+caps source not tuple",
            Map {
                body: fx.map_caps_f,
                captures: 1,
            },
            arr(i32t.clone(), 3),
            arr(f32t(), 3),
            p,
            false,
        ),
        (
            "Fold+caps ok",
            Fold {
                body: fx.fold_caps_f,
                captures: 1,
            },
            tup(&[i32t.clone(), f32t(), arr(i32t.clone(), 3)]),
            f32t(),
            p,
            true,
        ),
        (
            "Fold+caps acc mismatch",
            Fold {
                body: fx.fold_caps_f,
                captures: 1,
            },
            tup(&[i32t.clone(), i32t.clone(), arr(i32t.clone(), 3)]),
            f32t(),
            p,
            false,
        ),
        (
            "Fold+caps arity mismatch",
            Fold {
                body: fx.fold_caps_f,
                captures: 1,
            },
            tup(&[f32t(), arr(i32t.clone(), 3)]),
            f32t(),
            p,
            false,
        ),
        (
            "Fold tty not acc",
            Fold {
                body: fx.fold_f,
                captures: 0,
            },
            tup(&[f32t(), arr(i32t.clone(), 3)]),
            i32t.clone(),
            p,
            false,
        ),
        (
            "Fold elem vs body",
            Fold {
                body: fx.fold_f,
                captures: 0,
            },
            tup(&[f32t(), arr(f32t(), 3)]),
            f32t(),
            p,
            false,
        ),
        (
            "Fold not tuple",
            Fold {
                body: fx.fold_f,
                captures: 0,
            },
            arr(i32t.clone(), 3),
            f32t(),
            p,
            false,
        ),
    ]
}
