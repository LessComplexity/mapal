    pub fn get(mut self, name: &str) -> bool {
        self.rung(name).is_some_and(|r| *r)
    }

    /// `(self ∪ on) ∖ off`.
    pub fn with(mut self, arms: GpuArms) -> Self {
        for n in Self::NAMES {
            let r = self.rung(n).expect("a listed name");
            *r = (*r || arms.on.get(n)) && !arms.off.get(n);
        }
        self
    }
